#!/usr/bin/env python3
"""Create a separate CPU0/2 sensitivity source without editing frozen originals."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parent
original=root/'handoff.cpp';raw=original.read_bytes();text=raw.decode()
original_sha=hashlib.sha256(raw).hexdigest()
prior=json.loads((root/'results/dual_snapshot_before.json').read_text())
if original_sha!=prior['handoff.cpp']:raise SystemExit('frozen original hash mismatch')
old='pin(1);PBState logger_pb;'
if text.count(old)!=1:raise SystemExit('expected one Logger affinity expression')
text=text.replace(old,'pin(2);PBState logger_pb;')
lines=text.splitlines(keepends=True)
needle='configs.push_back({mode,shape,256,batch,4096})'
if sum(needle in line for line in lines)!=1:raise SystemExit('expected one supplementary queue4096 matrix line')
text=''.join(line for line in lines if needle not in line)
for old,new in [('for(size_t bytes:{64,256,1024})','for(size_t bytes:{256})'),('for(size_t batch:{1,32})','for(size_t batch:{32})')]:
 if text.count(old)!=1:raise SystemExit('matrix selector count mismatch: '+old)
 text=text.replace(old,new)
text='// Generated by prepare_cpu2.py; original handoff.cpp remains frozen.\n// Sensitivity only: Worker logical CPU0, Logger logical CPU2; 10 configurations.\n'+text
out=root/'handoff_cpu2.cpp';out.write_text(text)
meta={'original':'handoff.cpp','original_sha256':original_sha,'generated':'handoff_cpu2.cpp','generated_sha256':hashlib.sha256(out.read_bytes()).hexdigest(),
 'original_matches_primary_snapshot':True,'edits':['Logger pin(1) -> pin(2)','tail matrix -> {256}','queue batch matrix -> {32}','remove queue4096 supplementary matrix'],
 'configurations':10,'repeats':5,'minimum_run_seconds':0.3,'cpu_note':'Logical CPU0/2 chosen for reported distinct L1/L2 cache ids; this does not establish independent physical cores in a VM.'}
(root/'cpu2_generation.json').write_text(json.dumps(meta,indent=2)+'\n')
print(json.dumps(meta))
